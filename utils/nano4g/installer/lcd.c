static bool poll(uintptr_t address, uint32_t mask, uint32_t value,
                 uint32_t timeout)
{
    uint32_t start = now_us();
    unsigned budget = 200000;
    do
    {
        if ((REG32(address) & mask) == value)
            return true;
    } while (--budget && (uint32_t)(now_us() - start) < timeout);
    return false;
}

static bool write_bus(unsigned reg, uint32_t value)
{
    if ((LCD(0x1c) & 0x10) && !poll(LCD_BASE + 0x1c, 0x10, 0, 1000))
        return false;
    LCD(reg) = value;
    return true;
}

static bool mode(uint32_t value)
{
    if (!poll(LCD_BASE + 0x1c, 2, 2, 1000))
        return false;
    delay_us(1);
    LCD(0) = value;
    return true;
}

static bool command(uint8_t value, unsigned count, const uint8_t *bytes)
{
    if (!write_bus(4, value))
        return false;
    while (count--)
        if (!write_bus(0x40, *bytes++))
            return false;
    return true;
}

static bool sequence(const uint8_t *seq)
{
    for (;;)
    {
        unsigned op = *seq++;
        if (op == END)
            return true;
        if (op == SLEEP)
            delay_us(*seq++ * 10000u);
        else if (op == CMD)
        {
            uint8_t cmd = *seq++;
            unsigned count = *seq++;
            if (!command(cmd, count, seq))
                return false;
            seq += count;
        }
        else
            return false;
    }
}

static bool window(unsigned y, unsigned height)
{
    unsigned end = y + height - 1;
    const uint8_t columns[] = { 0, 0, 0, WIDTH - 1 };
    const uint8_t rows[] = { y >> 8, y, end >> 8, end };
    return mode(COMMAND_MODE) && command(0x2a, 4, columns) &&
           command(0x2b, 4, rows) && command(0x2c, 0, NULL) &&
           mode(FRAME_MODE);
}

